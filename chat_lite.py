class LiteChat:
    """Простая болтовня без нейросети. reply(text, strict=True) вернёт None, если намерение не найдено."""

    def __init__(self):
        self.last = None
        self.recent = []

    def _pick(self, variants):
        fresh = [v for v in variants if v not in self.recent] or variants
        choice = random.choice(fresh)
        self.recent = (self.recent + [choice])[-8:]
        return choice

    def reply(self, text, strict=False):
        text = (text or "").strip()
        if not text:
            return None
        words = _w(text)
        for name, fn in INTENTS:
            variants = fn(text, words)
            if variants:
                self.last = name
                out = self._pick(variants)
                if "{name}" in out:
                    out = out.format(name=USER["name"])
                return gendered(out)
        if strict:
            return None
        self.last = "fallback"
        is_question = "?" in text or _has(words, "почему", "зачем", "как", "что", "кто", "где", "когда", "сколько", "какой", "какая")
        if is_question and len(words) >= 3:
            return gendered(self._pick(QUESTION_FALLBACK))
        if len(words) <= 1:
            return gendered(self._pick(["Скажи что-нибудь поразвёрнутее, я не телепат.", "Одно слово? Я так могу и обидеться."]))
        return gendered(self._pick(REFLECT))
