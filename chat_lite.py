def _norm(text):
    text = text.lower().replace("ё", "е")
    return re.sub(r"[^\w\s]", " ", text).split()


def _has(words, *stems):
    """Есть ли слово, начинающееся с одной из основ."""
    return any(w.startswith(s) for w in words for s in stems)


def _phrase(text, *phrases):
    t = " " + " ".join(_norm(text)) + " "
    return any(" " + p + " " in t or (p.endswith("*") and " " + p[:-1] in t) for p in phrases)


