START = (r"^(капри[\s,]*)?(давай|включи|хочу|поставь|запусти|режим|расскажи|начнём|начни|поиграем|сыграем|"
         r"составь|помоги|посоветуй|советуй|поговори|мотивируй|замотивируй)\b")
EXIT = re.compile(r"^(капри[\s,]*)?(хватит|выйди из режима|выход из режима|выключи режим|обычный режим|"
                  r"давай обычный|закончили|закончим|всё на сегодня|все на сегодня|вернись в обычный)\b", re.IGNORECASE)
IDLE_EXIT = 30 * 60


class Roles:
    def __init__(self, capri):
        self.capri = capri
        self.role = None
        self.since = 0.0
        self.last = 0.0

    def active(self):
        if self.role and time.time() - self.last > IDLE_EXIT:
            self.exit(silent=True)
        return self.role

    def speak(self):
        return ROLES[self.role]["speak"] if self.role else True

    def match(self, text):
        """Ключ роли, если фраза просит её включить («давай сказку на ночь», «режим английского»)."""
        low = text.lower().replace("ё", "е").strip(" .!?")
        if len(low) > 90:
            return None
        bare = re.fullmatch(r"(капри[\s,]*)?(сказк\w+( на ночь)?|на ночь|квест\w*)", low)
        if not (bare or re.match(START, low) or re.match(r"^(капри[\s,]*)?(мне нужен|нужен|нужна) ", low)):
            return None
        for key, role in ROLES.items():
            if re.search(role["trigger"], low):
                return key
        return None

    def handle(self, text):
        """Текст ответа, если фраза включает или выключает режим, иначе None."""
        if self.active() and EXIT.match(text.strip()):
            return self.exit()
        key = self.match(text)
        if key and key != self.role:
            return self.enter(key)
        if self.role:
            self.last = time.time()
        return None

    def enter(self, key):
        c = self.capri
        if not c.has_brain():
            return ("Для этого режима нужна нейросеть. Подключи OpenRouter или OrcaRouter в config.json или запусти Ollama, "
                    "и мы поиграем.")
        role = ROLES[key]
        self.role, self.since, self.last = key, time.time(), time.time()
        self._apply()
        c.clear_context()  # новая роль — новый разговор, старые реплики не мешают
        c.role_changed.emit(key)
        return role["opener"]

    def exit(self, silent=False):
        if not self.role:
            return None
        name = ROLES[self.role]["name"]
        self.role = None
        self._apply()
        self.capri.clear_context()
        self.capri.role_changed.emit("")
        return None if silent else f"Режим «{name}» выключен. Вернулись к обычному разговору."

    def set(self, key):
        """Из выпадающего списка в окне чата: '' — обычный разговор. Возвращает реплику."""
        if not key:
            return self.exit()
        return self.enter(key) if key in ROLES else None

    def _apply(self):
        r = ROLES.get(self.role)
        persona.set_role(r["prompt"] if r else "", r["tokens"] if r else 0)
